const group = (
  prefix: string,
  expectedTop1: string,
  acceptedTop3: string[],
  questions: string[],
): SpreadEvalCase[] =>
  questions.map((question, index) => ({
    id: `${prefix}-${String(index + 1).padStart(2, '0')}`,
    question,
    expectedTop1,
    acceptedTop3,
  }));

