export const sourceFileForCard = (card: TarotCard): string => {
  if (card.arcana === 'major') {
    const number = card.rank;
    return `RWS Tarot ${number} ${card.nameEn.replace(/^The /, '')}.jpg`;
  }
  const prefix =
    card.suit === 'pentacles' ? 'Pents' : card.suit[0]!.toUpperCase() + card.suit.slice(1);
  const rank = ranks.find((item) => item.id === card.rank);
  if (!rank) throw new Error(`Missing source rank for ${card.id}`);
  return `${prefix}${rank.file}.jpg`;
};
